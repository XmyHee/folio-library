const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(m,p)=>m._compile(ts.transpileModule(fs.readFileSync(p,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText,p);
const {paperEvidence,coverUrlFor,titleCover,coverLines,addDocumentCover}=require('./src/lib/document-cover.ts');
(async()=>{
 assert.equal(paperEvidence('A short book with references').length,0);
 assert.equal(paperEvidence('Abstract only').length,0);
 assert.equal(paperEvidence('DOI 10.1234/abc').length,0);
 assert.equal(paperEvidence('Abstract: test DOI 10.1234/abc').length,1);
 assert.equal(paperEvidence('摘要 arXiv: 2401.12345').length,1);
 assert.equal(paperEvidence('', ['journal article']).length,1);
 const texts=[];
 global.document={createElement:()=>({width:0,height:0,getContext:()=>({fillRect(){},strokeRect(){},fillText:(t)=>texts.push(t),measureText:t=>({width:Array.from(t).length*20})}),toBlob:cb=>cb(new Blob(['generated']))})};
 const title='中文论文标题无空格也应完整换行'.repeat(10);
 assert.ok(coverLines({measureText:t=>({width:t.length*20})},title,100).every(line=>line.length<=5));
 assert.equal(await (await titleCover('中文论文','张三','pdf',true)).text(),'generated');
 assert.ok(texts.includes('张三'));
 texts.length=0;
 await titleCover(title,'张三、李四、王五、赵六'.repeat(15),'epub',true);
 assert.equal(texts.filter(t=>title.includes(t) && t.length>4).join(''),title);
 assert.ok(texts.every(t=>!t.includes('…')));
 const {PDFDocument}=require('pdf-lib'); const doc=await PDFDocument.create();doc.addPage([595,842]);
 const base={kind:'pdf',originalName:'中文论文 - 张三.pdf',rawTitle:'中文论文',authors:['张三'],identifiers:[],subjects:[],publisher:'',file:new Blob([await doc.save()]),hash:'original-hash',coverUrl:'blob:original',paperReasons:['摘要与DOI']};
 const paper=await addDocumentCover(base);
 assert.equal(paper.coverUrl,base.coverUrl);assert.equal(paper.hash,base.hash);assert.equal(paper.file,base.file);
 assert.equal(paper.coverPreference,'original'); assert.equal(coverUrlFor(paper),'blob:original');
 assert.equal(coverUrlFor({...paper,coverPreference:'original'}),'blob:original');
 URL.revokeObjectURL(paper.titleCoverUrl);
 const ordinary=await addDocumentCover({...base,paperReasons:[]});assert.equal(ordinary.titleCoverBlob,undefined);
 const epub=await addDocumentCover({...base,kind:'epub',paperReasons:[],coverUrl:undefined});
 assert.equal(epub.coverPreference,'title'); URL.revokeObjectURL(epub.titleCoverUrl);
 console.log('PASS: paper evidence, non-paper controls, CJK wrapping, title/author rendering, PDF/EPUB generation, preserved original bytes/hash/cover and reversible selection.');
})().catch(error=>{console.error(error);process.exitCode=1;});
